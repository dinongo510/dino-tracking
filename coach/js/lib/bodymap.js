/**
 * Tính toán chi tiết số liệu cho từng nhóm cơ bodymap:
 * - sets: tổng số hiệp (nhóm chính 1, nhóm phụ 0.5)
 * - sessions: số buổi tập có tác động
 * - pw: số hiệp / tuần (làm tròn 1 chữ số thập phân)
 * - level: 0 (0 hiệp), 1 (1–5), 2 (6–10), 3 (11–15), 4 (>15)
 */
export function calculateBodymapStats(rows, exById, from, to, weeksCount = 1) {
  const isLift = (r) => (r.load_kg > 0 && r.reps > 0) || r.reps > 0;
  const rawByFree = {}; // { [freeDbKey]: { sets, days: Set } }

  for (const r of rows) {
    if (!isLift(r) && !(r.distance_m > 0)) continue;
    if (from && r.day < from) continue;
    if (to && r.day > to) continue;

    const ex = exById.get(r.exercise_id);
    const prim = [...(ex?.primary_muscles || [])];
    const sec = [...(ex?.secondary_muscles || [])];
    if (r.distance_m > 0) {
      if (!prim.includes('quadriceps')) prim.push('quadriceps', 'calves');
      if (!sec.includes('hamstrings')) sec.push('hamstrings');
    }

    for (const m of prim) {
      const entry = (rawByFree[m] ||= { sets: 0, days: new Set() });
      entry.sets += 1;
      if (r.day) entry.days.add(r.day);
    }
    for (const m of sec) {
      const entry = (rawByFree[m] ||= { sets: 0, days: new Set() });
      entry.sets += 0.5;
      if (r.day) entry.days.add(r.day);
    }
  }

  const wCount = Math.max(1, weeksCount);
  const result = {};

  for (const [slug, info] of Object.entries(MUSCLE_INFO)) {
    let sets = 0;
    const allDays = new Set();
    for (const freeKey of info.freeDb) {
      const stat = rawByFree[freeKey];
      if (stat) {
        sets += stat.sets;
        for (const d of stat.days) allDays.add(d);
      }
    }
    const pw = sets / wCount;
    let level = 0;
    if (pw > 15) level = 4;
    else if (pw > 10) level = 3;
    else if (pw > 5) level = 2;
    else if (pw > 0) level = 1;

    result[slug] = {
      slug,
      label: info.label,
      sets: Math.round(sets * 10) / 10,
      sessions: allDays.size,
      pw: Math.round(pw * 10) / 10,
      level,
    };
  }

  return result;
}

/**
 * Trả về style CSS cho polygon cơ thể dựa trên sắc độ --h và cấp độ nhiệt (0..4)
 */
export function getBodymapPolygonStyle(slug, stats, isSelected = false) {
  const stat = stats[slug] || { level: 0 };
  const lvl = stat.level;

  let fill = 'rgba(255, 255, 255, 0.04)';
  let stroke = 'rgba(255, 255, 255, 0.12)';
  let strokeWidth = '3';
  let filter = 'none';

  if (lvl === 1) {
    fill = 'hsl(var(--h) 45% 36% / 0.55)';
    stroke = 'hsl(var(--h) 55% 48% / 0.7)';
  } else if (lvl === 2) {
    fill = 'hsl(var(--h) 65% 45% / 0.72)';
    stroke = 'hsl(var(--h) 75% 58% / 0.85)';
  } else if (lvl === 3) {
    fill = 'hsl(var(--h) 80% 54% / 0.88)';
    stroke = 'hsl(var(--h) 90% 70% / 0.95)';
    filter = 'drop-shadow(0 0 3px hsl(var(--h) 80% 55% / 0.4))';
  } else if (lvl === 4) {
    fill = 'hsl(var(--h) 92% 60% / 0.98)';
    stroke = 'hsl(var(--h) 96% 78% / 1)';
    filter = 'drop-shadow(0 0 6px hsl(var(--h) 90% 60% / 0.7))';
  }

  if (isSelected) {
    stroke = '#ffffff';
    strokeWidth = '14';
    filter = 'drop-shadow(0 0 10px #ffffff)';
  }

  return `fill:${fill};stroke:${stroke};stroke-width:${strokeWidth};cursor:pointer;transition:all .18s;${filter !== 'none' ? `filter:${filter};` : ''}`;
}
